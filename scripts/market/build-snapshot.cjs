#!/usr/bin/env node
/**
 * Builds src/features/market/snapshot.ts from the private research records.
 *
 *   node scripts/market/build-snapshot.cjs <records.json> [as-of YYYY-MM-DD]
 *
 * The records (third-party listings) stay out of the repository; only
 * BoyaCep's own rounded statistics are written. Rules: src/engine/market.ts
 * and docs/BOYACEP_PRICE_QUALITY_METHODOLOGY.md.
 */
require('./ts-require.cjs');
const fs = require('fs');
const path = require('path');
const { summarizePrices, roundPrice } = require('../../src/engine/market.ts');
const { provinceByName } = require('../../src/features/market/provinces.ts');

const [file, asOf = new Date().toISOString().slice(0, 10)] = process.argv.slice(2);
if (!file) throw new Error('usage: build-snapshot.cjs <records.json> [as-of]');
const records = JSON.parse(fs.readFileSync(file, 'utf8'));

/** One publisher is one source, however many pages its records came from. */
const publisher = (r) => (r.platform === 'armut' ? 'armut' : r.source);
/** Single-room jobs carry a minimum charge, so they get their own group and stay out of per-m² prices. */
const ROOM_MAX = 30;
const HOME_MAX = 300;

function observation(r, value) {
  return { value, observed: r.observed, sourceId: publisher(r), kind: r.kind };
}

/**
 * A firm's price list is one piece of evidence however many rows it has, so
 * its rows become one observation: their median, dated by the list.
 */
function collapsePriceLists(observations) {
  const lists = {};
  const out = [];
  for (const o of observations) {
    if (o.kind === 'firm_price_list') (lists[o.sourceId] ??= []).push(o);
    else out.push(o);
  }
  for (const rows of Object.values(lists)) {
    const values = rows.map((o) => o.value).sort((a, b) => a - b);
    const mid = Math.floor(values.length / 2);
    const value = values.length % 2 ? values[mid] : (values[mid - 1] + values[mid]) / 2;
    out.push({ ...rows[0], value, observed: rows.map((o) => o.observed).sort().at(-1) });
  }
  return out;
}

function groups(rows) {
  const usable = rows.filter((r) => r.price > 1000 && r.area_m2 > 0);
  const out = {};
  for (const scope of ['labour', 'materials']) {
    const mat = scope === 'labour' ? 'haric' : 'dahil';
    const homes = usable.filter((r) => r.materials === mat && r.area_m2 > ROOM_MAX && r.area_m2 <= HOME_MAX);
    const rooms = usable.filter((r) => r.materials === mat && r.area_m2 <= ROOM_MAX);
    out[scope] = {
      perM2: summarizePrices(collapsePriceLists(homes.map((r) => observation(r, r.price / r.area_m2))), asOf),
      room: summarizePrices(collapsePriceLists(rooms.map((r) => observation(r, r.price))), asOf),
      sources: [...new Set([...homes, ...rooms].map(publisher))].sort(),
    };
  }
  return out;
}

function rounded(summary, perM2) {
  const r = (v) => (v === null ? null : perM2 ? Math.round(v) : roundPrice(v));
  return { ...summary, median: r(summary.median), mean: r(summary.mean), low: r(summary.low), high: r(summary.high) };
}

const byProvince = {};
for (const r of records) {
  const p = provinceByName(r.province);
  if (!p) throw new Error(`unknown province ${r.province}`);
  (byProvince[p.code] ??= []).push(r);
}
const entries = Object.entries(byProvince).sort(([a], [b]) => a.localeCompare(b));
entries.push(['TR', records]);

const lines = entries.map(([code, rows]) => {
  const g = groups(rows);
  const scopes = Object.entries(g).map(
    ([scope, { perM2, room, sources }]) =>
      `    ${scope}: { perM2: ${JSON.stringify(rounded(perM2, true))}, room: ${JSON.stringify(rounded(room, false))}, sources: ${JSON.stringify(sources)} },`,
  );
  return `  '${code}': {\n${scopes.join('\n')}\n  },`;
});

const out = `// Generated by scripts/market/build-snapshot.cjs on ${asOf}. Do not edit by hand.
// BoyaCep's own statistics from public price research; see docs/BOYACEP_MARKET_DATA_SOURCES.md.
import type { MarketSnapshot } from './types';

export const SNAPSHOT_AS_OF = '${asOf}';

export const SNAPSHOT: MarketSnapshot = {
${lines.join('\n')}
};
`;
const target = path.resolve(__dirname, '../../src/features/market/snapshot.ts');
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${entries.length - 1} provinces + TR`);
